using Capacitor.Models.Transcripts.Harness.Claude;

namespace Capacitor.Models.Transcripts.Tests.Unit.Harness.Claude;

public class LocalCommandParserTests {
    static string Esc => ((char)0x1b).ToString();

    [Test]
    public async Task Parse_Null_ReturnsNone() {
        var r = LocalCommandParser.Parse(null);

        await Assert.That(r.Kind).IsEqualTo(LocalCommandParser.LocalCommandKind.None);
        await Assert.That(r.RemainingText).IsEqualTo("");
    }

    [Test]
    public async Task Parse_PlainText_ReturnsNoneWithTextIntact() {
        const string text = "just a normal prompt";

        var r = LocalCommandParser.Parse(text);

        await Assert.That(r.Kind).IsEqualTo(LocalCommandParser.LocalCommandKind.None);
        await Assert.That(r.RemainingText).IsEqualTo(text);
    }

    [Test]
    public async Task Parse_CommandWithoutArgs_ExtractsName() {
        const string text = "<command-name>/exit</command-name> <command-message>exit</command-message> <command-args></command-args>";

        var r = LocalCommandParser.Parse(text);

        await Assert.That(r.Kind).IsEqualTo(LocalCommandParser.LocalCommandKind.Command);
        await Assert.That(r.CommandName).IsEqualTo("/exit");
        await Assert.That(r.CommandArgs).IsEqualTo("");
        await Assert.That(r.RemainingText).IsEqualTo("");
    }

    [Test]
    public async Task Parse_CommandWithIndentedTags_ExtractsName() {
        // Matches the real on-disk shape: newlines + indentation between the tags.
        const string text = "<command-name>/rate-limit-options</command-name>\n            <command-message>rate-limit-options</command-message>\n            <command-args></command-args>";

        var r = LocalCommandParser.Parse(text);

        await Assert.That(r.Kind).IsEqualTo(LocalCommandParser.LocalCommandKind.Command);
        await Assert.That(r.CommandName).IsEqualTo("/rate-limit-options");
    }

    [Test]
    [Arguments("/loop", "5m /foo", "/loop", "5m /foo")]
    [Arguments("/plugin:a&amp;b", "Q&amp;A &lt;name&gt;", "/plugin:a&b", "Q&A <name>")]
    [Arguments("/rename", "&amp;lt;literal&amp;gt;", "/rename", "&lt;literal&gt;")]
    public async Task Parse_CommandWithArgs_ExtractsDecodedNameAndArgs(string name, string args, string expectedName, string expectedArgs) {
        var r = LocalCommandParser.Parse($"<command-name>{name}</command-name><command-args>{args}</command-args>");

        await Assert.That(r.Kind).IsEqualTo(LocalCommandParser.LocalCommandKind.Command);
        await Assert.That(r.CommandName).IsEqualTo(expectedName);
        await Assert.That(r.CommandArgs).IsEqualTo(expectedArgs);
        await Assert.That(LocalCommandParser.DisplayLabel(r)).IsEqualTo(expectedName + " " + expectedArgs);
    }

    [Test]
    public async Task Parse_Output_ExtractsText() {
        const string text = "<local-command-stdout>Worktree removed. 21 commits were discarded.</local-command-stdout>";

        var r = LocalCommandParser.Parse(text);

        await Assert.That(r.Kind).IsEqualTo(LocalCommandParser.LocalCommandKind.Output);
        await Assert.That(r.OutputText).IsEqualTo("Worktree removed. 21 commits were discarded.");
    }

    [Test]
    public async Task Parse_Output_StripsAnsiCodes() {
        var text = $"<local-command-stdout>{Esc}[32mLogin successful{Esc}[0m</local-command-stdout>";

        var r = LocalCommandParser.Parse(text);

        await Assert.That(r.Kind).IsEqualTo(LocalCommandParser.LocalCommandKind.Output);
        await Assert.That(r.OutputText).IsEqualTo("Login successful");
    }

    [Test]
    public async Task Parse_Output_WithoutClosingTag_CapturesToEnd() {
        const string text = "<local-command-stdout>partial output with no close";

        var r = LocalCommandParser.Parse(text);

        await Assert.That(r.Kind).IsEqualTo(LocalCommandParser.LocalCommandKind.Output);
        await Assert.That(r.OutputText).IsEqualTo("partial output with no close");
    }

    [Test]
    public async Task Parse_Caveat_ReturnsCaveatKind() {
        const string text = "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>";

        var r = LocalCommandParser.Parse(text);

        await Assert.That(r.Kind).IsEqualTo(LocalCommandParser.LocalCommandKind.Caveat);
        await Assert.That(r.RemainingText).IsEqualTo("");
    }

    [Test]
    public async Task Parse_CommandTakesPrecedenceOverOtherTags() {
        // Defensive: a command tag wins even if a stdout tag is also present.
        const string text = "<command-name>/x</command-name><local-command-stdout>out</local-command-stdout>";

        var r = LocalCommandParser.Parse(text);

        await Assert.That(r.Kind).IsEqualTo(LocalCommandParser.LocalCommandKind.Command);
        await Assert.That(r.CommandName).IsEqualTo("/x");
    }

    [Test]
    public async Task IsPure_PureCaveat_IsTrue() {
        const string text = "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>";

        await Assert.That(LocalCommandParser.IsPure(text, out var r)).IsTrue();
        await Assert.That(r.Kind).IsEqualTo(LocalCommandParser.LocalCommandKind.Caveat);
    }

    [Test]
    public async Task IsPure_PureCommandWithIndentedTags_IsTrue() {
        const string text = "<command-name>/clear</command-name>\n            <command-message>clear</command-message>\n            <command-args></command-args>";

        await Assert.That(LocalCommandParser.IsPure(text, out var r)).IsTrue();
        await Assert.That(r.Kind).IsEqualTo(LocalCommandParser.LocalCommandKind.Command);
    }

    [Test]
    public async Task IsPure_PureStdout_IsTrue() {
        await Assert.That(LocalCommandParser.IsPure("<local-command-stdout>Login successful</local-command-stdout>", out _)).IsTrue();
    }

    [Test]
    public async Task IsPure_PromptQuotingATag_IsFalse() {
        const string text = "Why is <command-name>/clear</command-name> showing up in my transcript?";

        await Assert.That(LocalCommandParser.IsPure(text, out var r)).IsFalse();
        await Assert.That(r.Kind).IsEqualTo(LocalCommandParser.LocalCommandKind.Command);
    }

    [Test]
    public async Task IsPure_PlainPromptAndNull_AreFalse() {
        await Assert.That(LocalCommandParser.IsPure("fix the login bug", out _)).IsFalse();
        await Assert.That(LocalCommandParser.IsPure(null, out _)).IsFalse();
    }

    [Test]
    public async Task DisplayLabel_CommandWithArgs_JoinsNameAndArgs() {
        LocalCommandParser.IsPure("<command-name>/deploy</command-name> <command-message>deploy</command-message> <command-args>prod --fast</command-args>", out var r);

        await Assert.That(LocalCommandParser.DisplayLabel(r)).IsEqualTo("/deploy prod --fast");
    }

    [Test]
    public async Task DisplayLabel_CommandWithEmptyArgs_IsNameOnly() {
        LocalCommandParser.IsPure("<command-name>/exit</command-name> <command-message>exit</command-message> <command-args></command-args>", out var r);

        await Assert.That(LocalCommandParser.DisplayLabel(r)).IsEqualTo("/exit");
    }

    [Test]
    public async Task DisplayLabel_Stdout_FirstLineOnly() {
        LocalCommandParser.IsPure("<local-command-stdout>Login successful\nsecond line ignored</local-command-stdout>", out var r);

        await Assert.That(LocalCommandParser.DisplayLabel(r)).IsEqualTo("Login successful");
    }

    [Test]
    public async Task DisplayLabel_Stdout_CappedAt200Chars() {
        LocalCommandParser.IsPure($"<local-command-stdout>{new string('x', 500)}</local-command-stdout>", out var r);

        var label = LocalCommandParser.DisplayLabel(r);

        await Assert.That(label.Length).IsEqualTo(201); // 200 + '…'
        await Assert.That(label).EndsWith("…");
    }

    [Test]
    public async Task DisplayLabel_BlankStdout_IsPlaceholder() {
        LocalCommandParser.IsPure("<local-command-stdout>   </local-command-stdout>", out var r);

        await Assert.That(LocalCommandParser.DisplayLabel(r)).IsEqualTo("Command output");
    }

    [Test]
    public async Task DisplayLabel_Caveat_IsFixedText() {
        LocalCommandParser.IsPure("<local-command-caveat>whatever</local-command-caveat>", out var r);

        await Assert.That(LocalCommandParser.DisplayLabel(r)).IsEqualTo("Local command context");
    }
}
