// Regenerates src/Capacitor.Cli.Core/Text/UnicodeNormalizationData.g.cs and the conformance fixture
// from the Unicode Character Database:
//
//   dotnet run scripts/generate-unicode-normalization.cs -- <ucd-dir> <version>
//
// <ucd-dir> holds UnicodeData.txt, DerivedNormalizationProps.txt and NormalizationTest.txt from
// https://www.unicode.org/Public/<version>/ucd/. Pick the version CharUnicodeInfo uses in the
// target runtime, so a code point the normalizer knows is one the runtime can classify.

using System.Globalization;
using System.IO.Compression;
using System.Text;

if (args.Length != 2) {
    Console.Error.WriteLine("usage: dotnet run scripts/generate-unicode-normalization.cs -- <ucd-dir> <version>");
    return 2;
}

var ucd     = args[0];
var version = args[1];
var repo    = Path.GetFullPath(Path.Combine(AppContext.GetData("EntryPointFileDirectoryPath") as string ?? ".", ".."));

var combiningClass = new SortedDictionary<int, int>();
var canonical      = new SortedDictionary<int, int[]>();

foreach (var line in File.ReadLines(Path.Combine(ucd, "UnicodeData.txt"))) {
    var f  = line.Split(';');
    var cp = Hex(f[0]);
    var cc = int.Parse(f[3], CultureInfo.InvariantCulture);
    if (cc != 0) combiningClass[cp] = cc;
    if (f[5].Length > 0 && !f[5].StartsWith('<')) canonical[cp] = f[5].Split(' ').Select(Hex).ToArray();
}

var excluded = new HashSet<int>();
foreach (var line in File.ReadLines(Path.Combine(ucd, "DerivedNormalizationProps.txt"))) {
    var data = line.Split('#')[0].Split(';', StringSplitOptions.TrimEntries);
    if (data.Length < 2 || data[1] != "Full_Composition_Exclusion") continue;
    var range = data[0].Split("..");
    for (int cp = Hex(range[0]), last = Hex(range[^1]); cp <= last; cp++) excluded.Add(cp);
}

var full = canonical.ToDictionary(e => e.Key, e => Expand(e.Key).ToArray());
var composition = canonical
    .Where(e => e.Value.Length == 2 && !excluded.Contains(e.Key))
    .OrderBy(e => e.Value[0]).ThenBy(e => e.Value[1])
    .ToList();

var src = new StringBuilder();
src.Append(CultureInfo.InvariantCulture, $$"""
    // <auto-generated>
    // Generated by scripts/generate-unicode-normalization.cs from the Unicode Character Database {{version}}.
    // Regenerate rather than edit.
    // </auto-generated>

    namespace Capacitor.Cli.Core.Text;

    static class UnicodeNormalizationData {
        public const string UnicodeVersion = "{{version}}";

    """);
Table("CombiningClassCodePoints", "int", combiningClass.Keys);
Table("CombiningClasses", "byte", combiningClass.Values);
Table("DecompositionCodePoints", "int", full.Keys.Order());
var offsets = new List<int> { 0 };
foreach (var cp in full.Keys.Order()) offsets.Add(offsets[^1] + full[cp].Length);
Table("DecompositionOffsets", "int", offsets);
Table("Decompositions", "int", full.Keys.Order().SelectMany(cp => full[cp]));
Table("CompositionFirsts", "int", composition.Select(e => e.Value[0]));
Table("CompositionSeconds", "int", composition.Select(e => e.Value[1]));
Table("Composites", "int", composition.Select(e => e.Key));
src.Append("}\n");

var dataPath = Path.Combine(repo, "src/Capacitor.Cli.Core/Text/UnicodeNormalizationData.g.cs");
Directory.CreateDirectory(Path.GetDirectoryName(dataPath)!);
File.WriteAllText(dataPath, src.ToString());

// The conformance file keeps its copyright header and drops the per-line comments, which are
// character names and make up most of its size.
var fixture = Path.Combine(repo, $"test/fixtures/unicode/NormalizationTest-{version}.txt.gz");
Directory.CreateDirectory(Path.GetDirectoryName(fixture)!);
using (var gz = new GZipStream(File.Create(fixture), CompressionLevel.SmallestSize))
using (var w = new StreamWriter(gz, new UTF8Encoding(false)) { NewLine = "\n" }) {
    var header = true;
    foreach (var line in File.ReadLines(Path.Combine(ucd, "NormalizationTest.txt"))) {
        if (header && line.StartsWith('#')) { w.WriteLine(line); continue; }
        header = false;
        var data = line.Split('#')[0].TrimEnd();
        if (data.Length > 0) w.WriteLine(data);
    }
}

Console.WriteLine($"{dataPath}: {combiningClass.Count} combining classes, {full.Count} decompositions, {composition.Count} compositions");
Console.WriteLine(fixture);
return 0;

IEnumerable<int> Expand(int cp) =>
    canonical.TryGetValue(cp, out var parts) ? parts.SelectMany(Expand) : [cp];

void Table<T>(string name, string type, IEnumerable<T> values) {
    src.Append(CultureInfo.InvariantCulture, $"\n    public static ReadOnlySpan<{type}> {name} => [\n");
    foreach (var row in values.Select(v => string.Format(CultureInfo.InvariantCulture, type == "byte" ? "{0}" : "0x{0:X}", v)).Chunk(12))
        src.Append("        ").Append(string.Join(", ", row)).Append(",\n");
    src.Append("    ];\n");
}

static int Hex(string s) => int.Parse(s, NumberStyles.HexNumber, CultureInfo.InvariantCulture);
